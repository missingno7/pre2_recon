/* Software sound mixer and MOD tracker (oracle: src/MODULE1.ASM).
 *
 * Covers MixChannel (cs:218F), TrackerTick (cs:227C), ProcessChannelCell (cs:2311), the
 * effect handlers reached through EffectJumpTable (DS:0B64h), and the block-mix part of
 * SbIrqHandler (cs:204D, entered at loc_20CF). The IRQ port work (SB ack, DMA, DSP 14h,
 * EOI) is not here: the block-mix body starts after it and ends before the EOI.
 *
 * Channel arrays are 8 bytes per field (channel offsets 0, 2, 4, 6). ChannelInstrument is
 * 0-based. Instrument records are 16 bytes at InstrumentTable + 16*index:
 *   +0 length (bytes), +2 volume word (default volume, includes the finetune byte in
 *   the high half), +4 loop start, +6 loop length (bytes), +8 sample offset, +10 sample
 *   segment. Sample positions are relative to the sample start; ChannelPos FFFFh = silent.
 * The volume table at DS:12C1h (VolumeTable[v*64 + s] = v*s >> 6, v = 0..64, s = 0..63) is
 * generated by the SB init code (loc_1E90) and has no label in src/.
 *
 * Original quirks kept here (each is exercised by tests/sound.py):
 *   - MixChannel loop wrap: when a looping sample passes its end inside a block, the
 *     position restarts at the raw loop start (relative to the sample, but used as an
 *     offset into the sample segment), the wrap iteration does not decrement CX (one extra
 *     byte past MixBuffer+167), and the new end is stored at ChannelEnd + 16*index (a
 *     stray store into the instrument records), not at this channel's ChannelEnd.
 *   - One-shot samples (loop length <= 2) that end inside a block fade: the previous
 *     output byte P is added to the next bytes as P, P-1, ... 1 while CX lasts.
 *   - Store at block end: the channel's ChannelEnd is compared with the position, so a
 *     channel whose end was moved by a stray store keeps the old end for the rest of the
 *     block.
 *   - The volume index is volume*64 + sample with 16-bit wrap and no clamp on the sample,
 *     so a sample byte >= 64 reads into the next volume row (xlat on DS:BX).
 *   - SongOrderPos wraps when its new low byte exceeds SongLength (cmp byte, al; jae), so
 *     position SongLength itself is still played (an unused table entry); 100h is kept.
 *   - Dxx: SongRow = AL - 1 sign-extended from 8 bits (00h gives FFFFh, 81h gives FF80h),
 *     SongOrderPos is incremented, and a row of 64 causes a second order increment.
 *   - Fxx: speed 0 reloads 0, so each row lasts 256 ticks.
 *   - ChannelVolumeSlide is cleared even for empty cells; instrument-only cells restart
 *     the sample and reset volume and phase; the effect runs for any nonzero cell.
 *   - MixSavedSp and MixSavedVolumeRow / MixChannelOffset keep their last values in DATA.
 */
#include "pre2.h"
#include "sound.h"
#include "startup.h"
#include "ports.h"
#include "platform.h"

#define VOLUME_TABLE DS_VolumeTable   /* 65 rows of 64 bytes, filled at SB set-up (loc_1E90) */

/* ds offset of a channel field, and of a field of the instrument record at `rec`. */
#define CH_OFF(name, ch)       ((uint16_t)(DS_##name + (ch)))
#define CHW(name, ch)          DW(CH_OFF(name, ch))
#define SET_CHW(name, ch, v)   SET_DW(CH_OFF(name, ch), (v))
#define REC_W(field, rec)      DW((uint16_t)(DS_##field + (rec)))

/* MixChannelOneShotFade: a one-shot sample ended inside the block. AX = P (the previous
 * output byte, looplen high byte is zero); P is added to the following bytes as P, P-1,
 * ..., 1 while CX lasts. The fade does not touch the channel's fields. */
static void one_shot_fade(uint16_t *di, uint16_t *cx)
{
    uint16_t a = DB((uint16_t)(*di - 1));
    if (a == 0) return;
    do {
        SET_DB(*di, DB(*di) + (uint8_t)a);
        *di = (uint16_t)(*di + 1);
        a--;
        if (a == 0) return;
    } while (--*cx != 0);
}

void MixChannel(uint16_t ch, uint16_t entry_sp)
{
    SET_DW(DS_MixChannelOffset, ch);
    uint16_t vol_row = (uint16_t)(CHW(ChannelVolume, ch) << 6);  /* volume*64, 16-bit */
    uint16_t step = CHW(ChannelStep, ch);
    uint16_t pos = CHW(ChannelPos, ch);
    if (pos == 0xFFFFu) return;                                /* silent (loc_227B) */

    uint16_t rec = (uint16_t)(CHW(ChannelInstrument, ch) << 4);
    uint16_t sample_seg = REC_W(word_0BDC, rec);
    uint16_t si = (uint16_t)(REC_W(word_0BDA, rec) + pos);
    uint16_t cx = (uint16_t)(CHW(ChannelEnd, ch) - pos);
    uint16_t phase = CHW(ChannelPhase, ch);
    uint16_t vrow = (uint16_t)(vol_row + VOLUME_TABLE);
    /* the original keeps the limit in SP: SP = sample offset + ChannelEnd (16-bit) */
    uint16_t limit = (uint16_t)(si + cx);
    SET_DW(DS_MixSavedSp, entry_sp);
    uint16_t di = DW(DS_MixBuffer);
    uint16_t count = MIX_BLOCK_BYTES;

    for (;;) {                                                 /* loc_21E6 */
        uint8_t s = rd8(sample_seg, si);
        si = (uint16_t)(si + 1);
        uint8_t v = DB((uint16_t)(vrow + s));                  /* xlat: DS:[BX+AL] */
        SET_DB(di, DB(di) + v);                                /* 8-bit add, carry dropped */
        di = (uint16_t)(di + 1);
        phase = (uint16_t)(phase + step);
        int16_t adv = (int8_t)(phase >> 8);                 /* cbw of DH */
        phase &= 0x00FFu;                                   /* xor dh,dh: keep the fraction */
        si = (uint16_t)(si + (uint16_t)adv);
        if (si > limit) {                                      /* MixChannelWrap */
            SET_DW(DS_MixSavedVolumeRow, vrow);
            uint16_t looplen = REC_W(word_0BD8, rec);
            if (looplen <= 2) {                                /* MixChannelOneShotFade */
                one_shot_fade(&di, &count);
                break;
            }
            si = REC_W(word_0BD6, rec);                        /* raw loop start (quirk) */
            /* stray store: ChannelEnd array indexed by the instrument's record offset */
            SET_DW((uint16_t)(DS_ChannelEnd + rec), (uint16_t)(looplen + si));
            continue;                                          /* jmp loc_21E6: CX unchanged */
        }
        if (--count == 0) break;
    }

    /* MixChannelStore */
    SET_ES(DATA_SEG);                                          /* mov ax, ds; mov es, ax (the silent return keeps ES) */
    SET_CHW(ChannelPhase, ch, phase);
    si = (uint16_t)(si - REC_W(word_0BDA, rec));
    if (CHW(ChannelEnd, ch) > si) {                            /* loc_2277 */
        SET_CHW(ChannelPos, ch, si);
        return;
    }
    si = 0xFFFFu;
    uint16_t looplen = REC_W(word_0BD8, rec);
    if (looplen > 2) {
        si = REC_W(word_0BD6, rec);
        SET_CHW(ChannelEnd, ch, (uint16_t)(looplen + si));
    }
    SET_CHW(ChannelPos, ch, si);
}

void SbMixBlock(uint16_t sp)
{
    SET_ES(DATA_SEG);                                          /* loc_20CF: ds = es = DATA */
    uint16_t di = DW(DS_MixBuffer);
    uint16_t left = DW(DS_SfxBytesLeft);
    if (left == 0) {                                           /* SfxSilenceBlock */
        for (uint16_t k = 0; k < MIX_BLOCK_BYTES; k++) SET_DB((uint16_t)(di + k), 0);
    } else {
        uint16_t n = left < MIX_BLOCK_BYTES ? left : MIX_BLOCK_BYTES;
        SET_DW(DS_SfxBytesLeft, (uint16_t)(left - n));
        uint16_t si = DW(DS_SfxPlayPos);
        uint16_t bank = DW(DS_SfxBankSegment);
        /* rep movsw: n/2 words; an odd n drops its last byte and leaves the block bytes
         * A6h-A7h unwritten (quirk). Offsets wrap within the segments. */
        uint16_t copy = (uint16_t)((n >> 1) * 2);
        for (uint16_t k = 0; k < copy; k++)
            SET_DB((uint16_t)(di + k), rd8(bank, (uint16_t)(si + k)));
        si = (uint16_t)(si + copy);
        di = (uint16_t)(di + copy);
        uint16_t zero = (uint16_t)(((MIX_BLOCK_BYTES - n) >> 1) * 2);  /* rep stosw */
        for (uint16_t k = 0; k < zero; k++) SET_DB((uint16_t)(di + k), 0);
        SET_DW(DS_SfxPlayPos, si);
    }
    if (CW(CS_OptionBits) & 0x40u) return;                     /* test cs:OptionBits, 40h */
    uint16_t call_sp = (uint16_t)(sp - 2);                     /* SP seen by MixChannel */
    MixChannel(0, call_sp);
    MixChannel(2, call_sp);
    MixChannel(4, call_sp);
    if (DW(DS_SfxBytesLeft) != 0) return;
    MixChannel(6, call_sp);
}

/* Effect handlers (EffectJumpTable order). */

/* Axy: x = high nibble -> slide +x; x = 0 -> slide -y (16-bit). */
void EffectVolumeSlide(uint16_t ch, uint8_t al)
{
    uint8_t hi = (uint8_t)(al >> 4);
    uint16_t slide = hi != 0 ? hi : (uint16_t)(0u - al);
    SET_CHW(ChannelVolumeSlide, ch, slide);
}

/* Bxx: order = AL (not range checked), row = FFFFh so the next row is 0. */
void EffectPositionJump(uint8_t al)
{
    SET_DW(DS_SongOrderPos, al);
    SET_DW(DS_SongRow, 0xFFFFu);
}

/* Cxx: volume = min(sign-extended AL, 40h); a negative AL (>= 80h) compares as large. */
void EffectSetVolume(uint16_t ch, uint8_t al)
{
    uint16_t v = (uint16_t)(int16_t)(int8_t)al;                /* cbw */
    if (v > 0x40u) v = 0x40u;                                  /* jbe: unsigned */
    SET_CHW(ChannelVolume, ch, v);
}

/* Dxx: row = sign-extended (AL - 1) (8-bit decrement, cbw), order incremented. */
void EffectPatternBreak(uint8_t al)
{
    uint8_t a = (uint8_t)(al - 1);
    SET_DW(DS_SongRow, (uint16_t)(int16_t)(int8_t)a);
    SET_DW(DS_SongOrderPos, (uint16_t)(DW(DS_SongOrderPos) + 1));
}

/* Fxx: speed = AL, used at the next row reload. */
void EffectSetSpeed(uint8_t al)
{
    SET_DB(DS_SongSpeed, al);
}

/* Jump through EffectJumpTable (16 code offsets, index = effect command). */
static void run_effect(uint16_t target, uint16_t ch, uint8_t al)
{
    switch (target) {
    case CS_EffectVolumeSlide:  EffectVolumeSlide(ch, al); break;
    case CS_EffectPositionJump: EffectPositionJump(al); break;
    case CS_EffectSetVolume:    EffectSetVolume(ch, al); break;
    case CS_EffectPatternBreak: EffectPatternBreak(al); break;
    case CS_EffectSetSpeed:     EffectSetSpeed(al); break;
    default: break;                                            /* IgnoreEffect */
    }
}

void ProcessChannelCell(uint16_t es, uint16_t si, uint16_t ch)
{
    SET_CHW(ChannelVolumeSlide, ch, 0);
    uint16_t w0 = rd16(es, si);                                /* note word */
    uint16_t w2 = rd16(es, (uint16_t)(si + 2));                /* instrument/effect, param */
    if ((w0 | w2) == 0) return;                                /* loc_2310: empty cell */

    uint8_t b1 = (uint8_t)(w0 >> 8);
    uint8_t b2 = (uint8_t)(w2 & 0xFF);                         /* instrument high bits, cmd */
    uint8_t b3 = (uint8_t)(w2 >> 8);                           /* effect parameter */
    uint16_t inst = (uint16_t)((b2 >> 4) | (b1 & 0x10));       /* 1..31, 0 = none */
    uint16_t effect = (uint16_t)(((b2 & 0x0Fu) << 8) | b3);
    SET_CHW(ChannelEffect, ch, effect);

    if (inst != 0) {                                           /* restart with the instrument */
        uint16_t idx = (uint16_t)(inst - 1);
        uint16_t rec = (uint16_t)(idx << 4);
        SET_CHW(ChannelInstrument, ch, idx);
        SET_CHW(ChannelPos, ch, 0);
        SET_CHW(ChannelEnd, ch, REC_W(InstrumentTable, rec));
        SET_CHW(ChannelVolume, ch, REC_W(word_0BD4, rec));
        SET_CHW(ChannelPhase, ch, 0);
    }
    uint16_t note = w0 & 0x7FFFu;
    if (note != 0) {
        SET_CHW(ChannelNote, ch, note);
        SET_CHW(ChannelStep, ch, DW((uint16_t)((note << 1) + DS_StepTable)));
    }
    uint16_t cmd = (uint16_t)(effect >> 8);
    run_effect(DW((uint16_t)(DS_EffectJumpTable + 2u * cmd)), ch, b3);
}

void TrackerTick(void)
{
    /* 1. volume slides, clamped to 0..40h */
    for (uint16_t ch = 0; ch < 8; ch += 2) {
        uint16_t slide = CHW(ChannelVolumeSlide, ch);
        if (slide != 0) {
            uint16_t v = (uint16_t)(CHW(ChannelVolume, ch) + slide);
            if (v & 0x8000u) v = 0;                            /* jns: negative -> 0 */
            if (v > 0x40u) v = 0x40u;
            SET_CHW(ChannelVolume, ch, v);
        }
    }
    /* 2. countdown; the row is processed when it reaches 0 */
    uint8_t ticks = (uint8_t)(DB(DS_SongTickCount) - 1);
    SET_DB(DS_SongTickCount, ticks);
    if (ticks != 0) return;
    SET_DB(DS_SongTickCount, DB(DS_SongSpeed));

    /* 3. cells of the current row for channels 0-3; es and si are latched before them */
    uint16_t pattern = DB((uint16_t)(DS_OrderTable + DW(DS_SongOrderPos)));
    uint16_t es = (uint16_t)((pattern << 6) + DW(DS_ModuleSegment));
    SET_ES(es);                                                /* ES stays on the pattern after the tick */
    uint16_t si = (uint16_t)((DW(DS_SongRow) << 4) + DW(DS_PatternDataOffset));
    ProcessChannelCell(es, si, 0);
    ProcessChannelCell(es, (uint16_t)(si + 4), 2);
    ProcessChannelCell(es, (uint16_t)(si + 8), 4);
    ProcessChannelCell(es, (uint16_t)(si + 12), 6);

    /* 4. next row; at 64 the next order (kept while its low byte <= SongLength) */
    uint16_t row = (uint16_t)(DW(DS_SongRow) + 1);
    SET_DW(DS_SongRow, row);
    if (row != 0x40u) return;
    uint16_t next = (uint16_t)(DW(DS_SongOrderPos) + 1);
    if (DB(DS_SongLength) < (uint8_t)next) next = 0;           /* cmp byte, al; jae */
    SET_DW(DS_SongOrderPos, next);
    SET_DW(DS_SongRow, 0);
}

/* ---- sound timing (moved from render.c: cs:1C65, MODULE1) ------------------------------ */

/* WaitSoundTicks (MODULE1 cs:1C6F): busy-wait until TimerTickCount is 3 or more away from
 * word_27EE (|difference| in 16 bits), then store the count. byte_6BE7 counts the advances
 * of exactly 3. The wait polls platform_poll(); a host that never advances the tick loops
 * forever, as the original does. */
void WaitSoundTicks(void)
{
    SET_DB(DS_byte_6BE7, 0);
    for (;;) {
        uint16_t ax = (uint16_t)(DW(DS_word_27EE) - CW(CS_TimerTickCount));
        if (ax & 0x8000) ax = (uint16_t)(-ax);            /* jns / neg */
        if (ax < 3) { platform_tick_wait(); continue; }
        if (ax == 3) SET_DB(DS_byte_6BE7, (uint8_t)(DB(DS_byte_6BE7) + 1));
        break;
    }
    SET_DW(DS_word_27EE, CW(CS_TimerTickCount));
}

/* StartSbBlock (cs:214E): start the first 168-byte block from PlayDmaRecord without mixing:
 * DMA channel 1 masked, flip-flop cleared, address and page from the record (+1 word, +0
 * byte), count A7h, unmasked; then DSP 14h with length A7h 00h (single-cycle 8-bit). */
void StartSbBlock(void)
{
    uint16_t bx = DW(DS_PlayDmaRecord);
    port_out8(0x0A, 5);
    port_out8(0x0C, 0);
    uint16_t addr = DW((uint16_t)(bx + 1));
    port_out8(0x02, (uint8_t)addr);
    port_out8(0x02, (uint8_t)(addr >> 8));
    port_out8(0x83, DB(bx));
    port_out8(0x03, 0xA7);
    port_out8(0x03, 0x00);
    port_out8(0x0A, 1);
    DspWriteWait(0x14);
    DspWriteWait(0xA7);
    DspWriteWait(0x00);
}

