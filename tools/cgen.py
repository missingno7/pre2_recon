"""Generate c/pre2_sym.h from the maintained ASM source (never edit the header by hand).

Every DATA label becomes `DS_<NAME>` (its ds offset), every code-segment label
`CS_<NAME>` (its code offset), and every `NAME equ value` in include/*.INC a `#define`.
Run after renaming or adding labels; tools/cbuild.py runs it automatically.
"""
from common import *
import re, where

def generate():
    labels = where.labels(case=True)
    lines = ['/* Generated by tools/cgen.py from src/ and include/: do not edit. */',
             '#ifndef PRE2_SYM_H', '#define PRE2_SYM_H', '']
    for name, linear in sorted(labels.items(), key=lambda x: x[1]):
        if linear >= 0x9FFC: lines.append(f'#define DS_{name} 0x{linear - 0x9FF0:04X}u')
        elif linear >= 0x200: lines.append(f'#define CS_{name} 0x{linear - 0x200:04X}u')
    for inc in sorted((ROOT/'include').glob('*.INC')):
        for m in re.finditer(r'^\s*(\w+)\s+equ\s+([0-9A-Fa-f]+h?|\d+)\s*(?:;.*)?$', inc.read_text(encoding='latin-1'), re.M):
            v = m.group(2); n = int(v[:-1], 16) if v[-1] in 'hH' else int(v)
            lines.append(f'#define {m.group(1).upper()} 0x{n:X}u')
    lines += ['', '#endif', '']
    out = ROOT/'c'/'pre2_sym.h'
    text = '\n'.join(lines)
    if not out.exists() or out.read_text() != text: out.write_text(text)
    return out

if __name__ == '__main__':
    print(generate())
