"""Build the native SDL3 host: c/*.c (translated game, platform models) + host/*.c.

    python tools/hostbuild.py      -> build/host/pre2.exe (+ SDL3.dll)

The initial memory image comes from our own ASM build (build/asm/PRE2.EXE, which
tools/verify.py proves identical to the original image): it is embedded as a generated C
array with its relocation list, so the native program needs neither PRE2.EXE nor any
emulator or Python at run time. Uses MSYS2 mingw64 gcc and SDL3 (metadata/sdl3.json).
"""
from common import *
from image import mz
import build, cgen, cbuild, subprocess, shutil, os

def embed(out):
    exe = build.assemble()
    h, image, rel, _ = mz(exe)
    lines = ['/* Generated by tools/hostbuild.py from build/asm/PRE2.EXE (our ASM build). */',
             '#include <stdint.h>',
             f'const uint32_t pre2_image_size = {len(image)}u;',
             'const uint8_t pre2_image[] = {']
    for i in range(0, len(image), 24):
        lines.append(','.join(str(b) for b in image[i:i + 24]) + ',')
    lines.append('};')
    lines.append(f'const uint32_t pre2_relocation_count = {len(rel)}u;')
    lines.append('const uint32_t pre2_relocations[] = {' + ','.join(str(s*16 + o) for s, o in rel) + '};')
    out.write_text('\n'.join(lines) + '\n')

def main():
    out = ROOT/'build'/'host'; out.mkdir(parents=True, exist_ok=True)
    embed(out/'image_data.c')
    cgen.generate()
    sdl = Path(read_json(ROOT/'metadata'/'sdl3.json')['local'])
    sources = [str(p) for p in sorted((ROOT/'c').glob('*.c'))] + [str(p) for p in sorted((ROOT/'host').glob('*.c'))] + [str(out/'image_data.c')]
    cmd = [str(cbuild.GCC), '-O2', '-g', '-std=c11', '-Wall', '-Wextra', '-Werror', '-Wno-unused-function', '-fwrapv',
           f'-I{sdl/"include"}', '-o', str(out/'pre2.exe'), *sources, f'-L{sdl/"lib"}', '-lSDL3']
    env = dict(os.environ, PATH=str(cbuild.GCC.parent) + os.pathsep + os.environ.get('PATH', ''))
    p = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if p.returncode: raise SystemExit(p.stdout + p.stderr)
    shutil.copyfile(sdl/'bin'/'SDL3.dll', out/'SDL3.dll')
    for dll in ('libwinpthread-1.dll',):
        src = cbuild.GCC.parent/dll
        if src.exists(): shutil.copyfile(src, out/dll)
    print(out/'pre2.exe')

if __name__ == '__main__':
    main()
